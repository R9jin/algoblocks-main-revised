# api/services/stats_utils.py
"""
Pure-Python distribution helpers shared by the admin analytics and the
phased-regression service.

These lived in admin_analytics_service.py (paired t-test support). They were
moved here unchanged so regression_service.py can reuse them WITHOUT importing
admin_analytics_service, which pulls in the database layer (psycopg2 +
DATABASE_URL) and would make the regression math impossible to unit test on a
machine with no database. scipy is deliberately not a dependency (serverless
bundle size), hence the hand-rolled regularized incomplete beta.
"""

import math
from typing import Optional


def _betacf(a: float, b: float, x: float) -> float:
    maxit, eps, fpmin = 200, 3.0e-12, 1.0e-300
    qab, qap, qam = a + b, a + 1.0, a - 1.0
    c = 1.0
    d = 1.0 - qab * x / qap
    if abs(d) < fpmin:
        d = fpmin
    d = 1.0 / d
    h = d
    for m in range(1, maxit + 1):
        m2 = 2 * m
        aa = m * (b - m) * x / ((qam + m2) * (a + m2))
        d = 1.0 + aa * d
        if abs(d) < fpmin:
            d = fpmin
        c = 1.0 + aa / c
        if abs(c) < fpmin:
            c = fpmin
        d = 1.0 / d
        h *= d * c
        aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2))
        d = 1.0 + aa * d
        if abs(d) < fpmin:
            d = fpmin
        c = 1.0 + aa / c
        if abs(c) < fpmin:
            c = fpmin
        d = 1.0 / d
        delta = d * c
        h *= delta
        if abs(delta - 1.0) < eps:
            break
    return h


def _betai(a: float, b: float, x: float) -> float:
    if x <= 0.0:
        return 0.0
    if x >= 1.0:
        return 1.0
    bt = math.exp(
        math.lgamma(a + b) - math.lgamma(a) - math.lgamma(b)
        + a * math.log(x) + b * math.log(1.0 - x)
    )
    if x < (a + 1.0) / (a + b + 2.0):
        return bt * _betacf(a, b, x) / a
    return 1.0 - bt * _betacf(b, a, 1.0 - x) / b


def _t_two_tailed_p(t: Optional[float], df: Optional[int]) -> Optional[float]:
    if t is None or not df or df <= 0:
        return None
    x = df / (df + t * t)
    return _betai(df / 2.0, 0.5, x)
